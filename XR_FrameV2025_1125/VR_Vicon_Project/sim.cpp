/*------------------------------------------------------------- cacheSkeleton
 * ?eS???????fu?E?p??N???L???b?V??c?????i?`????p?j
 *   parent ???g???? ezTracker ?g??? index ???????A???????? skeleton[] ??
 *   index ???????g????
 */
static void cacheSkeleton(ezTracker* body)
{
	skeleton_count = 0;
	for (int i = 0; i < _n_tracks; i++) skeleton[i].valid = false;

	for (int i = 0; i < _n_tracks; i++) {
		ezTrackDataT* d = body->getTrackData(i);
		if (d->id == -1) continue; //??}?? index ??????????

		BonePoseT* b = &skeleton[i];
		b->valid = true;
		b->x = d->x;
		b->y = d->y;
		b->z = d->z;
		b->roll = d->roll;
		b->pitch = d->pitch;
		b->yaw = d->yaw;
		b->parent = d->parent;
		strncpy(b->name, d->name, sizeof(b->name) - 1);
		b->name[sizeof(b->name) - 1] = '\0';
		skeleton_count++;
	}
}

