/*------------------------------------------------------------- DrawTrackedSkeleton
 * Vicon ???????M?????eS???????????????\??????
 *   draw.cpp ?? DrawScene() ?????????????i????C?e?B??g?O?f?????????????ez?f??j
 *   ?`????f???????????????A???M?f?[?^???????????????????????
 */
void DrawTrackedSkeleton(void)
{
	if (skeleton_count <= 0) return;

	glDisable(GL_LIGHTING);

	//---- ???i?e?q?j?????????? ----
	glLineWidth(3.0f);
	glColor3f(0.0f, 1.0f, 0.25f);
	glBegin(GL_LINES);
	for (int i = 0; i < _n_tracks; i++) {
		const BonePoseT* b = &skeleton[i];
		if (!b->valid) continue;
		if (b->parent < 0 || b->parent >= _n_tracks) continue;
		const BonePoseT* p = &skeleton[b->parent];
		if (!p->valid) continue;
		glVertex3f(b->x, b->y, b->z);
		glVertex3f(p->x, p->y, p->z);
	}
	glEnd();
	glLineWidth(1.0f);

	glEnable(GL_LIGHTING);

	//---- ????????c???\?? ----
	for (int i = 0; i < _n_tracks; i++) {
		const BonePoseT* b = &skeleton[i];
		if (!b->valid) continue;

		glPushMatrix();
		glTranslatef(b->x, b->y, b->z);

		if (b->parent < 0) {
			//???[?g?????p??N?????????????????W?????`??
			glRotatef(b->yaw, 0.0f, 1.0f, 0.0f);
			glRotatef(b->pitch, 1.0f, 0.0f, 0.0f);
			glRotatef(b->roll, 0.0f, 0.0f, 1.0f);

			glDisable(GL_LIGHTING);
			glBegin(GL_LINES);
			glColor3f(1.0f, 0.0f, 0.0f); glVertex3f(0.0f, 0.0f, 0.0f); glVertex3f(0.25f, 0.0f, 0.0f);
			glColor3f(0.0f, 1.0f, 0.0f); glVertex3f(0.0f, 0.0f, 0.0f); glVertex3f(0.0f, 0.25f, 0.0f);
			glColor3f(0.2f, 0.4f, 1.0f); glVertex3f(0.0f, 0.0f, 0.0f); glVertex3f(0.0f, 0.0f, 0.25f);
			glEnd();
			glEnable(GL_LIGHTING);

			glColor3f(1.0f, 0.5f, 0.0f);
			glutSolidCube(0.05); //???[?g???????e?????
		}
		else {
			glColor3f(1.0f, 0.8f, 0.0f);
			glutSolidCube(0.03);
		}

		glPopMatrix();
	}
}

